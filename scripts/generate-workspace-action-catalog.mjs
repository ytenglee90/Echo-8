import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Local documentation is the catalog source; this generator never accesses a model or network.
const source = JSON.parse(await readFile(new URL('../../deliveries/Echo-8-本地动作底座索引.json', import.meta.url), 'utf8'));
const catalog = {
  version: 1,
  categories: source.actionCategories.map(({ id, name, scope, candidateSourceKeys, representativeAcceptance }) =>
    ({ id, name, scope, sourceKeys: candidateSourceKeys, acceptance: representativeAcceptance })),
  crossCategory: source.crossCategoryCapabilities.map(({ id, name, scope, representativeAcceptance }) =>
    ({ id, name, scope, acceptance: representativeAcceptance })),
  scenarios: source.integrationScenarios.map(({ id, coverageIds, scenario, expected }) => ({ id, coverageIds, scenario, expected })),
};
if (catalog.categories.length !== 66 || catalog.crossCategory.length !== 27 || catalog.scenarios.length !== 11) {
  throw new Error('工作区清单数量与已确认的版本不一致，请检查来源');
}
const output = new URL('../src/plugins/workspace-actions/coverage-catalog.generated.ts', import.meta.url);
await writeFile(output, '// Generated by scripts/generate-workspace-action-catalog.mjs.\nexport const workspaceCoverageCatalog = ' + JSON.stringify(catalog, null, 2) + ' as const;\n', 'utf8');
process.stdout.write('Generated ' + fileURLToPath(output) + '\n');
